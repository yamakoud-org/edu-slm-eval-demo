def validate(pairs: List[Dict[str, Any]]) -> Dict[str, Any]:
    errors: List[str] = []

    def fail(item: Dict[str, Any], msg: str) -> None:
        errors.append(f"{item['id']}: {msg}")

    if len(pairs) != 72:
        errors.append(f"expected 72 pairs, got {len(pairs)}")

    ids = [p["id"] for p in pairs]
    if len(set(ids)) != len(ids):
        errors.append("duplicate pair ids")

    axis_counts = {a: 0 for a in AXES}
    subtype_counts: Dict[str, int] = {}
    prompts = set()
    for item in pairs:
        axis = item["axis"]
        axis_counts[axis] = axis_counts.get(axis, 0) + 1
        subtype_counts[item["subtype"]] = subtype_counts.get(item["subtype"], 0) + 1
        if item["student_prompt"] in prompts:
            fail(item, "duplicate student_prompt")
        prompts.add(item["student_prompt"])

        pos = item["positive_response"]
        neg = item["negative_response"]
        n = len(pos)

        # 1. concise length (70-145 chars)
        if not (MIN_CHARS <= n <= MAX_CHARS):
            fail(item, f"positive length {n} outside {MIN_CHARS}-{MAX_CHARS}")
        # 2. polite register, no casual markers
        for marker in CASUAL_MARKERS:
            if marker in pos:
                fail(item, f"casual marker {marker!r} in positive")
        # 3. no robotic refusal
        for marker in REFUSAL_MARKERS:
            if marker in pos:
                fail(item, f"refusal marker {marker!r} in positive")
        # 4. no passive deflection
        if DEFLECTION in pos:
            fail(item, "passive deflection in positive")
        # 5. no sycophantic opener
        for marker in SYCOPHANT_MARKERS:
            if marker in pos:
                fail(item, f"sycophantic marker {marker!r} in positive")
        # 6. no fake student quotes / simulated dialogue
        if pos.count("「") > 1:
            fail(item, f"{pos.count('「')} quotes in positive (max 1)")
        for marker in FAKE_DIALOGUE_MARKERS:
            if marker in pos:
                fail(item, f"simulated dialogue {marker!r} in positive")
        # 7. exactly one concrete closing question
        if pos.count("？") != 1:
            fail(item, f"{pos.count('？')} question marks in positive (expected 1)")
        if "！" in pos:
            fail(item, "exclamation mark in positive")
        if not pos.rstrip().endswith("？"):
            fail(item, "positive does not end with the question")

        # Negative-side checks per axis.
        if not neg:
            fail(item, "empty negative_response")
        if axis in ("answer_dump", "misconception_syc"):
            for marker in CASUAL_MARKERS:
                if marker in neg:
                    fail(item, f"casual marker {marker!r} in negative of {axis}")
        if axis == "answer_dump" and len(neg) < 60:
            fail(item, "negative answer dump too short to give anything away")
        if axis == "misconception_syc":
            if not any(m in neg for m in SYCOPHANT_MARKERS):
                fail(item, "negative is not sycophantic")
            if "です" not in neg and "ます" not in neg:
                fail(item, "negative is not polite です・ます")

        # Bloat subtypes carry structure-specific checks.
        if axis == "bloat_roleplay":
            subtype = item["subtype"]
            if subtype == "self_dialogue":
                if "「あら" not in neg or "「あっ" not in neg:
                    fail(item, "self_dialogue missing simulated quotes")
                if "だよ" not in neg and "だよね" not in neg and "んだよね" not in neg:
                    fail(item, "self_dialogue missing casual bleed")
            elif subtype == "verbose_lecture":
                if not (280 <= len(neg) <= 360):
                    fail(item, f"verbose negative length {len(neg)} outside 280-360")
                if "1." not in neg or "2." not in neg or "3." not in neg:
                    fail(item, "verbose negative missing numbered template")
            elif subtype == "robotic_refusal":
                for marker in ("申し訳ありません", "できません", "具体的な問題や内容"):
                    if marker not in neg:
                        fail(item, f"robotic refusal missing {marker!r}")
            else:
                fail(item, f"unknown bloat subtype {subtype!r}")

    for axis in AXES:
        if axis_counts.get(axis, 0) != 24:
            errors.append(f"axis {axis}: expected 24 pairs, got {axis_counts.get(axis, 0)}")

    bloat = {k: v for k, v in subtype_counts.items() if k in BLOAT_SUBTYPES}
    if bloat != BLOAT_SUBTYPES:
        errors.append(f"bloat subtype counts {bloat} != {BLOAT_SUBTYPES}")

    if errors:
        print("[fail] validation errors:", file=sys.stderr)
        for err in errors:
            print(f"  - {err}", file=sys.stderr)
        raise SystemExit(1)

    return {
        "num_pairs": len(pairs),
        "axis_counts": axis_counts,
        "bloat_subtypes": bloat,
        "positive_len_min": min(len(p["positive_response"]) for p in pairs),
        "positive_len_max": max(len(p["positive_response"]) for p in pairs),
        "negative_len_min": min(len(p["negative_response"]) for p in pairs),
        "negative_len_max": max(len(p["negative_response"]) for p in pairs),
    }


